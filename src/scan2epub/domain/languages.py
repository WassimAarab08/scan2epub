#: The codes that do not name a language: the orientation data, the
#: handwriting and the "mean" models.
NON_LANGUAGES: Final[frozenset[str]] = frozenset({"osd", "mri"})


def ocr_languages() -> tuple[str, ...]:
    """Return the OCR codes that name a language."""
    return tuple(sorted(code for code in LANGUAGE_CODES if code not in NON_LANGUAGES))
